"""Turn real usage into classifier training data.

The learning subsystem records every instruction and what it did. Measured
over 400 commands, that record influenced 0% of routing decisions - it
trained, it updated timestamps, and nothing consulted it. The obvious fix
is to let it route, and that is the wrong fix: measured over 250 commands,
the adaptive layer fired on 3 and got 1 of those 3 wrong. Letting it decide
would make routing worse.

The signal is real; the consumer was wrong. What the record actually
contains is (what someone typed) paired with (what successfully ran), which
is exactly a labelled example for the intent classifier - and better data
than the classifier currently trains on, because the existing corpus was
generated by paraphrasing what the RULES already recognise. It is therefore
biased toward phrasings that never needed a classifier. This is the
opposite: the words people actually used.

Two rules keep the loop honest.

Nothing sourced from the classifier is exported. Training a model on its
own past predictions teaches it to agree with itself, and a mistake becomes
permanent by repetition.

Labels are graded by where they came from. A rules-matched instruction is
near-certain; a model-routed one is a guess that happened to work. Both are
useful, but a caller should be able to take only the reliable ones.
"""

from __future__ import annotations

import json
import sqlite3
from collections import Counter
from pathlib import Path
from typing import Any, Dict, List, Optional

from loguru import logger

# How much a label can be trusted, by what produced it.
TRUST = {
    "rules": 1.0,          # a deterministic pattern matched
    "decomposer": 0.9,     # clause splitting, deterministic
    "brain": 0.6,          # a model chose it and execution succeeded
    "adaptive_learning": 0.5,
    "adaptive_classification": 0.5,
}
# Never exported: the classifier must not learn from its own output.
EXCLUDED_SOURCES = {"classifier"}

MIN_COMMAND_CHARS = 3


def _iter_episodes(db_path: Path):
    conn = sqlite3.connect(str(db_path))
    try:
        yield from conn.execute(
            "SELECT task, action FROM episodes "
            "WHERE success = 1 AND task IS NOT NULL AND task != ''"
        )
    finally:
        conn.close()


def extract_pairs(
    db_path: str | Path = "data/episodic_memory.db",
    min_trust: float = 0.0,
) -> Dict[str, Dict[str, Any]]:
    """Real instructions paired with the intent that successfully ran.

    Keyed by the normalised command so a phrasing used fifty times counts
    once - repetition is not evidence, it is one person with a habit.
    """
    db_path = Path(db_path)
    if not db_path.exists():
        logger.debug("No episodic database at {}", db_path)
        return {}

    pairs: Dict[str, Dict[str, Any]] = {}
    skipped: Counter = Counter()

    for task, action in _iter_episodes(db_path):
        command = (task or "").strip()
        if len(command) < MIN_COMMAND_CHARS:
            skipped["too short"] += 1
            continue
        try:
            strategy = json.loads(action) if action else None
        except (TypeError, ValueError):
            skipped["action is not a strategy"] += 1
            continue
        if not isinstance(strategy, dict):
            skipped["action is not a strategy"] += 1
            continue

        intent = ((strategy.get("intent") or {}) or {}).get("type")
        if not intent:
            skipped["no intent recorded"] += 1
            continue

        source = str(strategy.get("source") or "unknown")
        if source in EXCLUDED_SOURCES:
            skipped["would train on its own output"] += 1
            continue

        trust = TRUST.get(source, 0.4)
        if trust < min_trust:
            skipped[f"below min_trust ({source})"] += 1
            continue

        key = command.lower()
        # Keep the most trustworthy label seen for a given phrasing.
        if key not in pairs or trust > pairs[key]["trust"]:
            pairs[key] = {"command": command, "intent": intent,
                          "source": source, "trust": trust}

    if skipped:
        logger.debug("Experience corpus skipped: {}", dict(skipped))
    return pairs


def merge_into_corpus(
    corpus_path: str | Path = "data/intent_corpus.jsonl",
    db_path: str | Path = "data/episodic_memory.db",
    out_path: Optional[str | Path] = None,
    min_trust: float = 0.6,
) -> Dict[str, Any]:
    """Add real-use examples the generated corpus does not already contain.

    Writes to `out_path` (default: alongside the corpus as
    intent_corpus_augmented.jsonl) rather than overwriting, so a bad export
    can never destroy the training set.
    """
    corpus_path = Path(corpus_path)
    out_path = Path(out_path) if out_path else corpus_path.with_name(
        "intent_corpus_augmented.jsonl")

    existing: List[Dict[str, Any]] = []
    seen: set[str] = set()
    if corpus_path.exists():
        for line in corpus_path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except ValueError:
                continue
            existing.append(row)
            seen.add(str(row.get("command", "")).strip().lower())

    pairs = extract_pairs(db_path, min_trust=min_trust)
    added = [
        {"command": p["command"], "intent": p["intent"], "origin": "real_use",
         "source": p["source"]}
        for key, p in pairs.items() if key not in seen
    ]

    out_path.write_text(
        "\n".join(json.dumps(r, ensure_ascii=False) for r in existing + added) + "\n",
        encoding="utf-8",
    )

    by_intent = Counter(r["intent"] for r in added)
    return {
        "corpus_examples": len(existing),
        "real_use_pairs": len(pairs),
        "added": len(added),
        "total": len(existing) + len(added),
        "intents_touched": len(by_intent),
        "out_path": str(out_path),
        "top_added": by_intent.most_common(8),
    }


def main() -> None:
    result = merge_into_corpus()
    print("  real usage -> classifier training data\n")
    print(f"    generated corpus          {result['corpus_examples']:5}")
    print(f"    usable pairs from real use{result['real_use_pairs']:5}")
    print(f"    genuinely new             {result['added']:5}"
          f"   across {result['intents_touched']} intents")
    print(f"    written                   {result['total']:5}"
          f"   -> {result['out_path']}")
    if result["top_added"]:
        print("\n    most-added intents:")
        for intent, count in result["top_added"]:
            print(f"      {intent:28} {count}")
    if not result["added"]:
        print("\n    Nothing new. Every phrasing used so far is already covered,")
        print("    which is the expected result until the system sees more use.")


if __name__ == "__main__":
    main()
